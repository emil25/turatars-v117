import { pathToFileURL } from 'node:url';
import fs from 'node:fs';
const playwrightPath = process.env.V120_PLAYWRIGHT_PATH;
const edgePath = process.env.V120_EDGE_PATH;
if (!playwrightPath || !edgePath || !fs.existsSync(playwrightPath) || !fs.existsSync(edgePath)) {
  console.log('V120 browser GPS test SKIP (set V120_PLAYWRIGHT_PATH and V120_EDGE_PATH to run locally)');
  process.exit(0);
}
const playwright = await import(pathToFileURL(playwrightPath).href);
const { chromium } = playwright.default || playwright;
import assert from 'node:assert/strict';

const browser = await chromium.launch({ headless: true, executablePath: edgePath });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
page.on('pageerror', e => errors.push(String(e)));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
await page.addInitScript(() => {
  const t = { id: 't-v120-test', title: 'V120 GPS teszt', place: 'Csíkszereda', status: 'tervezés', date: '', difficulty: 'Könnyű', lengthKm: 4, ascent: 120, durationH: 2, tags: [], desc: 'GPS célzott teszt', img: '', coords: null, waypoints: [], gpx: null, timeline: [], gear: [], participants: [], cars: [], food: [], safety: [], notes: '', photos: [], eventRef: null, eventCat: '', meeting: '', weatherChecked: false, shareCode: null, tasks: [], noteStream: [], budget: [] };
  if (!window.localStorage.getItem('turavaros_v1')) window.localStorage.setItem('turavaros_v1', JSON.stringify({ users: { 'u-v120': { id: 'u-v120', name: 'V120 teszt', email: 'v120@test.local', pass: 'cloud:test', city: 'Csíkszereda', onboarded: true, joined: '2026-09-12' } }, data: { 'u-v120': { tours: [t], wishlist: [], savedEvents: [], equipment: [], journal: [], teams: [], goals: { km: 300, tours: 12, summits: 3 }, goalList: null, notifDismiss: [], prefs: { weather: true, reminders: true }, aiChat: [], templates: [], terepi: [], reportAck: {}, challenges: null, widgets: null } }, session: 'u-v120' }));
  let first = true;
  const point = (lat, lng, timestamp = Date.now()) => ({ coords: { latitude: lat, longitude: lng, accuracy: 8, altitude: 520 }, timestamp });
  const geo = { getCurrentPosition(success) { success(point(46.36, 25.80)); }, watchPosition(success) { window.__geoSuccess = success; if (first) { first = false; setTimeout(() => success(point(46.3608, 25.8012, Date.now() + 30000)), 20); } return 7; }, clearWatch() {} };
  Object.defineProperty(navigator, 'geolocation', { configurable: true, value: geo });
});
await page.goto('http://127.0.0.1:4174/#/tura/t-v120-test', { waitUntil: 'networkidle' });
await page.locator('[data-modal]').evaluateAll(els => els.forEach(e => e.remove()));
await page.evaluate(() => document.querySelector('#v120-start').click());
await page.waitForURL(/#\/tura-live\/t-v120-test/);
await page.waitForTimeout(100);
assert.ok(await page.locator('#v120-root').count());
assert.match(await page.locator('#v120-status').textContent(), /Folyamatban/);
assert.equal(await page.locator('#v120-points').textContent(), '2');
assert.match(await page.locator('#v120-distance').textContent(), /0\.\d+ km/);
await page.evaluate(() => document.querySelectorAll('[data-modal]').forEach(e => e.remove()));
await page.evaluate(() => document.querySelector('#v120-pause').click());
await page.waitForTimeout(30);
assert.match(await page.locator('#v120-status').textContent(), /Szüneteltetve/);
await page.evaluate(() => document.querySelector('#v120-resume').click());
assert.match(await page.locator('#v120-status').textContent(), /Folyamatban/);
const before = await page.locator('#v120-points').textContent();
await page.evaluate(() => window.__geoSuccess({ coords: { latitude: 47.2, longitude: 26.8, accuracy: 5, altitude: 520 }, timestamp: Date.now() + 60000 }));
await page.waitForTimeout(40);
assert.equal(await page.locator('#v120-points').textContent(), before);
await page.evaluate(() => document.querySelector('#v120-finish').click());
await page.locator('#cfm-yes').click();
await page.waitForTimeout(100);
assert.match(await page.locator('#v120-status').textContent(), /Befejezve/);
assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('turavaros_v1')).data['u-v120'].tours[0].liveTrack.status), 'finished');
await page.reload({ waitUntil: 'networkidle' });
await page.waitForTimeout(500);
assert.match(await page.locator('#v120-status').textContent(), /Befejezve/);
assert.ok((await page.evaluate(() => document.documentElement.scrollWidth)) <= 390);
assert.equal(errors.length, 0, errors.join('\n'));
console.log('V120 browser GPS test PASS');
await browser.close();
